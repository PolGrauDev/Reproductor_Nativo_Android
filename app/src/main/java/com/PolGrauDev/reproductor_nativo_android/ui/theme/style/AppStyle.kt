package com.PolGrauDev.reproductor_nativo_android.ui.theme.style

/**
 * The three bespoke visual styles the user can pick in Ajustes. Each one reskins every screen
 * (colors, fonts, shapes, decorative chrome) independently of Material 3 — see
 * `ui/theme/style/<style>/` for the token/component sets and `ui/screens/style/<style>/` for the
 * per-style screen implementations.
 */
enum class AppStyle {
    PAPEL,
    STICKERS,
    FANZINE,
}
